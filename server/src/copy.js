export function confirmedDate(term) {
  return `${termSentence(term)}\n\nЕсли дата не та, нажмите «Изменить дату».`
}

export function scheduleText(user) {
  const place = esc(zoneLabel(user.tz))
  return `Буду присылать заметку каждый день в ${esc(user.send_time)}, часовой пояс: ${place}.\n\n${HELP}`
}

export function pausedText(user) {
  const place = esc(user.tz ? zoneLabel(user.tz) : 'часовой пояс ещё не выбран')
  const time = esc(user.send_time || '09:00')
  return `Рассылка на паузе. Время было ${time}, ${place}. Снова включить — /resume.`
}
